import type { ChoiceDef, GameEvent } from "@/game/event-types";
import type { Life } from "@/game/types";

function turn(
  id: string,
  title: string,
  body: string,
  choices: ChoiceDef[],
  when: (life: Life) => boolean,
  extra: Partial<GameEvent> = {},
): GameEvent {
  return {
    id,
    title,
    body,
    choices,
    major: true,
    minAge: extra.minAge,
    weight: extra.weight ?? 2.2,
    facet: extra.facet ?? "mind",
    urgent: extra.urgent,
    when,
  };
}

